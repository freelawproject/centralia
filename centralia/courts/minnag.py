# ---------------------------------------------------------------------------
# minnag's declared facts, measured over all 41 records of /assets/minnag.
# ---------------------------------------------------------------------------
# The cover is on page 1 on 40 records and on page 2 on 185a-5 (whose page 1
# is the slip alone). Nothing needs a third page.
_MAX_PAGES = 2
# On page 2 the top band is the letter's own running head ('Thomas M. Canan /
# October 17, 2014 / Page 3') or the slip number repeated. Core drops both.
_TOP_BAND = 0.12
# AT THE RAIL / INDENTED. The office sets a 36pt first-line indent on every
# record; the addressee never leaves its rail by more than 10.2pt (852's
# centred second line of an agency name).
_RAIL_TOL = 14.0
_INDENT_MIN = 24.0
# SAME-ROW PIECES. 358a3 letter-spaces its topic line into six pieces
# 19.9-20.9pt apart; the real columns stand 62-325pt apart.
_SAME_ROW_SPLIT = 24.0
# THE SLIP'S HEADNOTE RUN: rows on the slip's own leading continue it, a
# blank line ends it. Leading measured 12.0-16.5pt; the blank line 22.9-29.5.
_RUN_LEADING = 1.55
# THE NUMBER is short and stands right of the slip's own measure.
_DOCKET_WIDTH_MAX = 0.45
_DOCKET_DX_MIN = 0.35
# THE DATELINE: short, and far right of the rail on every record.
_DATE_WIDTH_MAX = 0.35
_DATE_DX_MIN = 0.25
# THE LETTERHEAD's masthead is 24pt where the body is 11-13pt.
_MASTHEAD_SIZE = 16.0
# A BARE SLIP is the whole of page 1: ten rows or fewer, all in the top 40%.
_SLIP_ONLY_ROWS = 10
_SLIP_ONLY_BAND = 0.40

_MONTHS = (r"Jan(?:uary)?|Feb(?:ruary)?|Mar(?:ch)?|Apr(?:il)?|May"
           r"|Jun(?:e)?|Jul(?:y)?|Aug(?:ust)?|Sep(?:t(?:ember)?)?"
           r"|Oct(?:ober)?|Nov(?:ember)?|Dec(?:ember)?")
# A DATELINE, through forty years of scanners: 'February 20, 2025',
# 'March 11, --1998', "November 5, I ']98", 'December I 5, 1 998'.
_DATELINE = re.compile(rf"^(?:{_MONTHS})\b[\s.,]+[0-9IlO]", re.I)
_DATE_CLEAN = re.compile(rf"\b({_MONTHS})\b\s*([0-9]{{1,2}}),?\s*"
                         r"([12][0-9]{3})\b", re.I)

# THE OPINION NUMBER. Digits, letters, hyphens and the reporter's stray
# punctuation, with no word of three or more letters — that last clause is
# what keeps '222 South Ninth Street' out. 'Index No.' is the one label the
# office ever prints in front of it.
_NUMBER = re.compile(r"^(?:Index\s+No\.\s*)?[0-9]"
                     r"[0-9A-Za-z().,;:'\"’”\-/ ]*$")
_LONG_WORD = re.compile(r"[A-Za-z]{3,}")
# A CROSS-REFERENCE: '(Cr. Ref. 170c)', '(cr.ref. 169x)', '(er. ref. 494a,
# 785d)', 'cr ref 185a-5; 385a)'. Two words, one scanner-proof shape.
_XREF = re.compile(r"^[\(\[]?\s*(?:c|e)r[.\s]*ref\b", re.I)
# The subject line. 'Re:', 'RE:', 'Re :' — and nothing else on this paper
# opens with those two letters and a colon.
_SUBJECT = re.compile(r"^Re\s*:\s*", re.I)
# How the letter was sent. Not a fact about the opinion, but it is printed
# in the cover and it is not the addressee.
_DELIVERY = re.compile(r"^(?:VIA|Via|BY|By)\s+(?:E-?MAIL|E-?mail|FAX|Fax"
                       r"|HAND|Hand|U\.S\.|Facsimile|FACSIMILE)\b")
# A POSTAL row: where the official is, not who they are. Closed vocabulary,
# used only to say which addressee rows name a person and an office.
_POSTAL = re.compile(
    r"^(?:P\.?\s?O\.?\s+Box\b|Suite\b|\d)"
    r"|\b(?:Street|St\.|Avenue|Ave\.|Road|Rd\.|Boulevard|Blvd\.?|Drive"
    r"|Dr\.|Lane|Ln\.|Place|Pl\.|Way|Court|Ct\.|Parkway|Pkwy\.?|Box"
    r"|Suite|Ste\.|Floor|Tower|Bldg\.?|Building|Center|Centre)\b"
    r"|,\s*[A-Z]{2}\s+\d{5}|,\s*(?:Minnesota|MN)\s+\d{5}", )
_ZIP = re.compile(r"\b\d{5}(?:-\d{4})?\b")


def _norm(text: str) -> str:
    return " ".join(text.split())


def _unwrap(text: str) -> str:
    """Strip the reporter's wrapper, not the number's own parentheses:
    '(Cr. ref. 185b-2)' loses its brackets, '379C-8(c)' keeps them."""
    body = re.sub(r"^Index\s+No\.\s*", "", _norm(text)).strip(",; ")
    while body.startswith("(") and body.endswith(")") \
            and body.count("(") == body.count(")"):
        body = body[1:-1].strip(",; ")
    # 'cr ref 185a-5; 385a)' — a scan that lost its opening bracket.
    if body.endswith(")") and body.count(")") > body.count("("):
        body = body[:-1].strip(",; ")
    return body


def _has_ink(text: str) -> bool:
    """A scan speckle ('\\', '-', '----· ..') is not a row. Core records
    those as stamps; this reader passes over them and claims nothing."""
    return bool(re.search(r"[0-9A-Za-zÀ-ɏ]", text))


def _rows(pm) -> list[list]:
    """One group per printed row, split where the page set two things more
    than 24pt apart — the number beside the addressee (159a-3), a second
    addressee column (484e-1), the delivery notation and the telephone
    (280k). Nothing else on this paper leaves that much white."""
    buckets: dict[float, list] = {}
    order: list[float] = []
    for line in sorted(pm.lines, key=lambda l: (l.top, l.x0)):
        if not _has_ink(line.plain):
            continue
        key = round(line.top, 1)
        if key not in buckets:
            buckets[key] = []
            order.append(key)
        buckets[key].append(line)
    out: list[list] = []
    for key in order:
        row = sorted(buckets[key], key=lambda l: l.x0)
        chunk = [row[0]]
        pieces = []
        for piece in row[1:]:
            if piece.x0 - chunk[-1].x1 > _SAME_ROW_SPLIT:
                pieces.append(chunk)
                chunk = [piece]
            else:
                chunk.append(piece)
        pieces.append(chunk)
        out.append(pieces)
    return out


def _page_rows(model) -> list[tuple]:
    """(pm, top, [pieces]) for every row of the first two pages, with page
    2's running-head band left to core."""
    out: list[tuple] = []
    for pm in model.pages[:_MAX_PAGES]:
        height = pm.height or 792.0
        for pieces in _rows(pm):
            top = min(p[0].top for p in pieces)
            if pm.number > 1 and top < height * _TOP_BAND:
                continue
            out.append((pm, top, pieces))
    return out


def _extent(groups) -> tuple[float, float]:
    """(rail, right) over a set of piece-groups."""
    xs = [p.x0 for g in groups for p in g]
    x1s = [p.x1 for g in groups for p in g]
    return (min(xs) if xs else 0.0), (max(x1s) if x1s else 0.0)


def _find_dateline(rows) -> tuple[int, int] | None:
    """The hinge: the letter's date, short and far right of its page's rail.
    Returns (row index, piece index) or None."""
    for ridx, (pm, _top, pieces) in enumerate(rows):
        wide = [g for _p, _t, gs in rows if _p is pm for g in gs
                if max(l.x1 for l in g) - min(l.x0 for l in g)
                > (pm.width or 612.0) * 0.25]
        rail, right = _extent(wide or pieces)
        measure = max(right - rail, 100.0)
        for pidx, group in enumerate(pieces):
            text = _norm(" ".join(l.plain for l in group))
            width = max(l.x1 for l in group) - min(l.x0 for l in group)
            dx = min(l.x0 for l in group) - rail
            if (_DATELINE.match(text)
                    and width <= measure * _DATE_WIDTH_MAX
                    and dx >= measure * _DATE_DX_MIN):
                return ridx, pidx
    return None


def _is_docket(text: str, dx: float, width: float, measure: float,
               run_open: bool) -> bool:
    """The opinion number, or a cross-reference to another one."""
    # A cross-reference is two words through forty years of scanners and is
    # never held to the width cap: 59a-32 prints '(Cr. Ref. to 125a-66,
    # 477b-34, 484a-1, 484e-1)', 225pt of a 467pt measure.
    if _XREF.match(text):
        return True
    if width > measure * _DOCKET_WIDTH_MAX:
        return False
    # 'Index No. 622-i-11' is the one long-word form the office prints.
    if not text.lower().startswith("index no"):
        if not _NUMBER.match(text) or _LONG_WORD.search(text):
            return False
    if dx >= measure * _DOCKET_DX_MIN:
        return True
    # …or standing below the topic statement across a blank line.
    return not run_open


@decider("headmatter.read", court="minnag")
def read_headmatter_minnag(model, geom, **_):
    """Read the AG's index slip and the letter's cover, or NOTHING."""
    if not model.pages:
        return NOTHING
    rows = _page_rows(model)
    if not rows:
        return NOTHING

    ctx = _Ctx()
    hinge = _find_dateline(rows)

    # ---- the bare slip: page 1 is the reporter's index and nothing else --
    if hinge is None:
        page1 = [r for r in rows if r[0].number == 1]
        height = model.pages[0].height or 792.0
        if (not page1 or len(page1) > _SLIP_ONLY_ROWS
                or max(r[1] for r in page1) > height * _SLIP_ONLY_BAND):
            return NOTHING
        _read_slip(ctx, page1)
        if not ctx.items:
            return NOTHING
        ctx.crit["headmatter_style"] = STYLE_SLIP
        return _finish(ctx)

    hidx, hpiece = hinge
    _read_slip(ctx, rows[:hidx])
    _read_cover(ctx, rows, hidx, hpiece)
    if not ctx.items:
        return NOTHING
    ctx.crit["headmatter_style"] = STYLE_LETTER
    return _finish(ctx)


def _read_slip(ctx, slip) -> None:
    """The reporter's index: the topic statement, then the number.

    The statement is a RUN — rows at the slip's rail on its own leading —
    and the number is what stands outside it. Where the office prints its
    letterhead, the 24pt masthead opens a banner that runs to the dateline.
    """
    if not slip:
        return
    per_page: dict[int, tuple[float, float]] = {}
    for pm, _top, pieces in slip:
        wide = [g for g in pieces
                if max(l.x1 for l in g) - min(l.x0 for l in g)
                > (pm.width or 612.0) * 0.25]
        rail, right = per_page.get(pm.number, (1e9, 0.0))
        for group in (wide or pieces):
            rail = min(rail, min(l.x0 for l in group))
            right = max(right, max(l.x1 for l in group))
        per_page[pm.number] = (rail, right)

    # The letterhead opens at the masthead and closes at the dateline.
    banner_from = None
    for idx, (_pm, top, pieces) in enumerate(slip):
        if any(l.size and l.size >= _MASTHEAD_SIZE
               for g in pieces for l in g):
            banner_from = idx
            break

    run_open = False
    prev_top: float | None = None
    prev_page: int | None = None
    prev_size = 12.0
    for idx, (pm, top, pieces) in enumerate(slip):
        rail, right = per_page.get(pm.number, (0.0, 612.0))
        measure = max(right - rail, 100.0)
        if prev_top is not None and prev_page == pm.number:
            step = top - prev_top
            if step > prev_size * _RUN_LEADING:
                run_open = False
                ctx.gap()
        elif prev_page is not None and prev_page != pm.number:
            run_open = False
            ctx.gap()
        prev_top, prev_page = top, pm.number
        prev_size = max((l.size or 12.0) for g in pieces for l in g)

        if banner_from is not None and idx >= banner_from:
            for group in pieces:
                ctx.emit(group, "banner", rail)
            continue

        for group in pieces:
            text = _norm(" ".join(l.plain for l in group))
            x0 = min(l.x0 for l in group)
            width = max(l.x1 for l in group) - x0
            dx = x0 - rail
            if _is_docket(text, dx, width, measure, run_open):
                ctx.docket(text)
                ctx.emit(group, "docket", rail)
                continue
            run_open = dx <= _RAIL_TOL
            ctx.headnote.append(text)
            ctx.emit(group, "headnotes", rail)



def _read_cover(ctx, rows, hidx, hpiece) -> None:
    """The dateline and the letter's cover: how it was sent, who it is to,
    and what about.

    Ends at the salutation, which is left in the stream — it is the letter's
    first line and core opens the writing on it.
    """
    below = rows[hidx + 1:]
    look = below[:15]
    if look:
        rail = min(l.x0 for _p, _t, gs in look for g in gs for l in g)
        right = max(l.x1 for _p, _t, gs in look for g in gs for l in g)
    else:
        rail, right = _extent(rows[hidx][2])
    measure = max(right - rail, 100.0)

    # ---- the dateline, measured against the LETTER's rail ----------------
    pm, top, pieces = rows[hidx]
    ctx.gap()
    for pidx, group in enumerate(pieces):
        if pidx == hpiece:
            text = _norm(" ".join(l.plain for l in group))
            found = _DATE_CLEAN.search(text)
            ctx.crit["decision_date"] = (
                f"{found.group(1)} {found.group(2)}, {found.group(3)}"
                if found else text)
            ctx.emit(group, "date", rail)
        else:
            # 280k prints its telephone beside the date; that is the
            # letterhead, wherever the office chose to set it.
            ctx.emit(group, "banner", rail)

    prev_top: float | None = top
    prev_page: int | None = pm.number
    prev_size = max((l.size or 12.0) for g in pieces for l in g)
    for pm, top, pieces in below:
        head = pieces[0]
        text = _norm(" ".join(l.plain for l in head))
        dx = min(l.x0 for l in head) - rail
        subject = bool(_SUBJECT.match(text))
        # ---- the two ends of the cover, read on the row's FIRST piece ----
        if not subject:
            if dx <= _RAIL_TOL and text.rstrip().endswith(":") \
                    and len(text) <= 70:
                return                      # the salutation: the letter's
            if dx >= _INDENT_MIN:           # first paragraph, or a head
                return
        if prev_top is not None and prev_page == pm.number \
                and top - prev_top > prev_size * _RUN_LEADING:
            ctx.gap()
        elif prev_page is not None and prev_page != pm.number:
            ctx.gap()
        prev_top, prev_page = top, pm.number
        prev_size = max((l.size or 12.0) for g in pieces for l in g)

        for group in pieces:
            body = _norm(" ".join(l.plain for l in group))
            x0 = min(l.x0 for l in group)
            width = max(l.x1 for l in group) - x0
            gdx = x0 - rail
            if _SUBJECT.match(body):
                ctx.crit.setdefault("title", _norm(_SUBJECT.sub("", body)))
                ctx.emit(group, "title", rail)
            elif _DELIVERY.match(body):
                ctx.delivery.append(body)
                ctx.emit(group, "case-info", rail)
            elif gdx >= measure * _DOCKET_DX_MIN \
                    and _is_docket(body, gdx, width, measure, run_open=True):
                # 159a-3 prints the number and its cross-reference in the
                # RIGHT MARGIN, beside the first two addressee rows. Only
                # the margin is read that way here: at the rail every piece
                # of this band is the addressee, and '222 South Ninth
                # Street' would otherwise have to be argued out of it.
                ctx.docket(body)
                ctx.emit(group, "docket", rail)
            else:
                ctx.addressee.append(body)
                ctx.emit(group, "caption", rail)


def _finish(ctx) -> dict:
    ctx.crit["court"] = "Office of the Minnesota Attorney General"
    if ctx.numbers:
        ctx.crit["docket_number"] = ctx.numbers[0]
        if ctx.numbers[1:]:
            ctx.crit["other_dockets"] = ctx.numbers[1:]
    if ctx.addressee:
        # The printed cover, kept whole…
        ctx.crit["caption"] = list(ctx.addressee)
        # …and beside it the official who asked, taken as the rows above the
        # first postal line — the person and the office they hold.
        #
        # NOT `parties`. There are none: an AG opinion is one office
        # answering one official, and the render joins `parties` with ' v. '
        # ('Erich Martens v. Executive Director v. Minnesota State High
        # School League'), which states an adversity the paper does not.
        named: list[str] = []
        for row in ctx.addressee:
            if _POSTAL.search(row) or _ZIP.search(row):
                break
            named.append(row.rstrip(",;"))
        if named:
            # 'Ronald R. Frauenshuh, Sr.' keeps its period — the
            # generational suffix is part of the name.
            ctx.crit["case_name"] = named[0].rstrip(",; ")
    # The delivery notation is not the case's HISTORY and is not written
    # there; it is tinted `case-info` in the block, where it is printed.
    return {"criteria": ctx.crit, "items": ctx.items, "attorneys": [],
            "dropped": ctx.dropped, "consumed": ctx.consumed,
            "anchor_ids": [],
            # EVERY RECORD IN THIS SERIES IS AN OPINION. The office issues
            # them under Minn. Stat. § 8.07 and the reporter cites them 'Op.
            # Atty. Gen. 1035'. Core reads 39 of the 41 that way already and
            # calls 280k and 280l-1 orders, on nothing the paper says — so
            # the type is declared, not inferred.
            "doc_type_final": m.DocType.OPINION}


class _Ctx:
    """The emit buffer: what the walk placed, and where it came from."""

    def __init__(self):
        self.items: list = []
        self.dropped: list = []
        self.consumed: set[int] = set()
        self.crit: dict = {}
        self.headnote: list[str] = []
        self.addressee: list[str] = []
        self.delivery: list[str] = []
        self.numbers: list[str] = []

    def docket(self, text: str) -> None:
        """'3-a; 390a6' is two numbers on one row; '(Cr. Ref. 170c)' is a
        pointer to another opinion. Both are kept, in printed order."""
        body = _norm(text)
        if _XREF.match(body):
            self.numbers.append(_unwrap(body))
            return
        for piece in body.split(";"):
            piece = _unwrap(piece)
            if piece:
                self.numbers.append(piece)

    def emit(self, group: list, role: str, rail: float) -> None:
        parts = sorted(group, key=lambda l: l.x0)
        if not parts:
            return
        first = parts[0]
        text = ""
        for part in parts:
            piece = line_markup(part)
            text = (text.rstrip() + " " + piece.lstrip()) if text.strip() \
                else piece
        self.items.append(m.HmLine(
            text=text, prov=m.Prov(first.page, tuple(p.id for p in parts)),
            align=m.Align.LEFT, x0=first.x0, size=first.size or 0.0,
            bold=all(bool(p.all_bold) for p in parts),
            rel=round(max(first.x0 - rail, 0.0), 1), role=role))
        self.consumed.update(p.id for p in parts)

    def gap(self, lines: int = 1) -> None:
        if self.items and not isinstance(self.items[-1], m.Gap):
            self.items.append(m.Gap(lines=lines))

    def drop(self, group: list, kind: str) -> None:
        parts = sorted(group, key=lambda l: l.x0)
        self.dropped.append(m.Dropped(
            text=_norm(" ".join(p.plain for p in parts))[:400],
            prov=m.Prov(parts[0].page, tuple(p.id for p in parts)),
            kind=kind or "furniture"))
        self.consumed.update(p.id for p in parts)


