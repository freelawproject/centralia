"""Office of the Minnesota Attorney General ('minnag').

THIS IS NOT A COURT'S PAPER AND IT HAS NO CAPTION. There are no parties, no
docket, no panel and no tribunal below. What the 41 records publish is a
LETTER — the Attorney General answering a question a named public official
put to the office under Minn. Stat. § 8.07 — and the reporter's INDEX SLIP
that the Opinions office prints above it so the letter can be filed and
cited. Two documents, one sheet, and the reader's whole job is to tell them
apart and stop before the letter's first word.

    ┌────────────────────────────────────────────────────────────────┐
    │ AUCTIONEERS: LICENSES: COUNTIES:  Time-limited online   the    │
    │ auction sales are not subject to auctioneer-licensing   index  │
    │ requirements.  Minn. Stat. §§ 330.01-330.13 (2012).     slip   │
    │                                            16-b     ← the number
    │                                     (cr.ref. 169x)  ← its cross-refs
    │                                                                │
    │                     STATE OF MINNESOTA          the letterhead │
    │              OFFICE OF THE ATTORNEY GENERAL      (2 records)   │
    │  KEITH ELLISON                102 STATE CAPITOL                │
    │  ATTORNEY GENERAL             ST. PAUL, MN 55155-1609          │
    │                                                                │
    │                    October 17, 2014             the dateline   │
    │                                                                │
    │  VIA EMAIL: mmanders@bloomingtonmn.gov          how it was sent│
    │  Thomas M. Canan                                the addressee: │
    │  Sr. Assistant Olmsted County Attorney          the official   │
    │  151 4th Street SE                              who asked, and │
    │  Rochester, MN 55904-3710                       where          │
    │                                                                │
    │      Re:  Application of Auctioneer Licensing … the subject    │
    │                                                                │
    │  Dear Mr. Canan:                        ← THE LETTER BEGINS    │
    │      I thank you for your correspondence received on …         │
    └────────────────────────────────────────────────────────────────┘

THE DATELINE IS THE HINGE, AND IT IS THE DISPATCH. Above it stands the
reporter's slip; below it stands the letter's cover. It is the one row every
letter sets the same way — a bare month-day-year, standing 0.40-0.44 of the
measure right of the rail and filling 0.13-0.22 of it — and it is the only
landmark that survives this corpus. Everything else moves: the number prints
flush right on 39 records, at the LEFT margin on 125a-28, as the labelled
'Index No. 622-i-11' at the rail on 622i-11, at a 396pt tab on 62b, in the
right margin BESIDE the addressee on 159a-3, and ABOVE the headnote on
185a-5. The topic line is set in caps on 35 records and title case on 6, and
opens page 1 on 40 of the 41 — 185a-5 prints the number over it. A reader
keyed to any of that reads a handful of records; keyed to the dateline it
reads all 38 that carry a letter.

TWO RAILS, NOT ONE. The slip and the letter are set by different hands and
they do not share a left edge: 1035 sets the slip at 79.6 and the letter at
72.0, 3a_390a6 sets the slip at 32.0 and the letter at 72.0, 185a-5 sets the
slip on page 1 and the letter on page 2. So the rail is measured twice, above
the dateline and below it, and 'at the rail' means at the rail of your own
half of the sheet. Measured across one rail, the addressee of 3a_390a6 reads
as a 41pt indent and the block falls apart.

    THE LETTER'S RAIL IS THE LEFTMOST INK BELOW THE DATELINE, not the
    leftmost WIDE row: 484e-1 sets its whole page-1 body as a block
    quotation at 98.5 and its addressee at 64.5, so a rail taken from the
    wide rows lands 34pt INSIDE the block it is supposed to bound. Read
    that way, no addressee row anywhere in the corpus stands more than
    10.8pt off its rail (852 centres 'Labor and Industry' under the agency
    name above it).

WHERE THE SLIP ENDS. Its topic statement is a paragraph — a run of rows at
the slip rail on the slip's own leading, 5.6-16.5pt — and the number is what
stands outside that run: right of it (39 records), or after it across a blank
line of 22.9pt or more (125a-28, 622i-11). Both tests are needed and neither
alone is enough. Width
alone takes '473.3997.', the last line of 229a's citation string, which is a
short numeric row at the rail in the middle of the headnote; the run test
keeps it where it belongs. Position alone misses 125a-28, which prints the
number under the headnote at the same 36pt margin.

THE NUMBER'S VOCABULARY IS CLOSED, and it has to be, because '222 South
Ninth Street' is also a short row far right of the rail — it is the fourth
line of 484e-1's SECOND addressee column. An AG opinion number is digits,
letters and hyphens with no word of three or more letters in it ('1001 K',
'379C-8(c)', '16lb-7', '3-a; 390a6', '622a6; cr 161b-11'); a cross-reference
opens 'cr ref' / '(Cr. Ref.' / '(er.ref.' — the same two words through forty
years of scanners.

SAME-ROW PIECES ARE REAL HERE and they mean three different things. 159a-3
prints the number in the right margin beside the addressee's first line;
484e-1 addresses TWO law firms in two columns; 280k sets 'Via Email and U.S.
Mail' beside the addressee and its telephone beside the dateline. So a row is
split where its pieces stand more than 24pt apart and each piece is read on
its own, keeping its own offset from the rail — 484e-1's second column comes
back at rel 239 and renders in the column the page set it in, which is one
better than v1, where the two firms are run together on five lines. 24pt is
chosen against the paper: 358a3 letter-spaces its topic line into six pieces
19.9-20.9pt apart and they are one row, not six.

THE READER STOPS AT THE SALUTATION AND DOES NOT CLAIM IT. 'Dear Mr. Canan:'
is the letter's first line, not the cover's last, and it is what core opens
the writing on — a claim that took it would leave 41 records with no anchor
for the paragraph beneath it. The stop is measured on the row's FIRST piece
only (484e-1's second column stands 240pt in and would otherwise end the
block four rows early):

  * at the rail and ending in a colon  → the salutation. Not always 'Dear':
    430 and 355a write 'Mr. Engblom:' and 'Ms. Manderschied:'.
  * indented 24pt or more              → the letter's first paragraph, or a
    bold centred head ('FACTS', 'BACKGROUND', 'QUESTION'). The first-line
    indent is 36pt on every record the office set digitally.
  * …unless it opens 'Re:' or 'RE:', which is the subject line: 17 records
    print one, 16 of them 36-45pt in and 268l at the rail.

A BARE SLIP IS STILL A READING. Three records (280l-1 and the two copies of
624c-4) print the index slip alone on page 1 and nothing else: the letter's
own first page is not in the scan, and page 2 opens under a running head with
the answer already in progress. There is no dateline to hinge on, so the
reader claims the slip if and only if page 1 is nothing BUT slip — ten rows
or fewer, all of them in the top 40% of the sheet. Anything else with no
dateline is not this paper and the reader returns NOTHING. A fourth record,
185a-5, prints the slip alone on page 1 and the LETTER'S COVER on page 2;
that one hinges normally, on a dateline the walk finds one page down.

    280l-1 is the record this reading costs a grade. Read as it is, its
    opinion begins 'also stated: "As members can only be arrested …"' and
    quality scores a `decap`; before the slip was claimed, the reporter's
    topic line stood in as the opinion's opening paragraph and hid the fact
    that the letter's first page is missing. The C is the true reading.

THE LETTERHEAD IS TWO RECORDS OUT OF FORTY-ONE and it is found by its type,
not its words: 'STATE OF MINNESOTA' is set at 24pt where the body is 11-13pt,
and nothing else on this paper is over 15pt. Everything between that row and
the dateline — the office name, the Capitol address, the telephone, and the
Attorney General's own name in the left margin — is the same banner.

WHAT IS NOT READ HERE. The signature is at the FOOT of the letter ('Sincerely,
/ KEITH ELLISON / Attorney General') and core already finds it; taking it
would be reaching into a writing. The page-1 footer strip — the office
address and 'An Equal Opportunity Employer Who Values Diversity', set at
7.6pt (11 records) or 8.0pt (2) against a 12pt body — stands below the
letter's first paragraph and so lies inside the writing; it is core's to drop
and is REPORTED, not patched (see the module note at the foot of this
file).
"""

